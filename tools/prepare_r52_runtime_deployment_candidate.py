def sha(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def read(path): return json.loads(Path(path).read_text('utf-8-sig'))
def write(path, document):
    path = Path(path).resolve()
    if not path.is_relative_to(CANDIDATE.resolve()): raise ValueError('Candidate-only output required')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + '\n', 'utf8')
    return path
def relative(name):
    p = PurePosixPath(name)
    if not name or p.is_absolute() or ':' in name or '\\' in name or any(x in ('', '.', '..') for x in name.split('/')):
        raise ValueError('Bounded component path required: ' + name)
    return p
def reference(parent, row, key):
    rel = relative(row[key]); source = (parent / rel.as_posix()).resolve()
    if not source.is_relative_to(parent.resolve()) or not source.is_file() or sha(source) != row['sha256']:
        raise ValueError('Actual component SHA/path differs: ' + str(source))
    return rel.as_posix(), source
def exact_authority(doc, epoch, fingerprint, path):
    if isinstance(doc, dict):
        if 'directory_fingerprint' in doc and doc['directory_fingerprint'] != fingerprint:
            raise ValueError('Mixed directory fingerprint in ' + path)
        if 'epoch' in doc and doc['epoch'] != epoch: raise ValueError('Mixed epoch in ' + path)
        for key, value in doc.items(): exact_authority(value, epoch, fingerprint, path + '/' + key)
    elif isinstance(doc, list):
        for i, value in enumerate(doc): exact_authority(value, epoch, fingerprint, path + '/' + str(i))
def java_uuid(text):
    raw = bytearray(hashlib.md5(text.encode()).digest()); raw[6] = (raw[6] & 15) | 48; raw[8] = (raw[8] & 63) | 128
    return str(uuid.UUID(bytes=bytes(raw)))
def expected_controllers(bundle, owner, directory, cannon=None):
    """Exact actual new manifest identities; no station/id/count substitution."""
    if not directory.get('routes') or any(not isinstance(r.get('motion_profile'),dict) or r['motion_profile'].get('type')!='continuous_upright' for r in directory['routes']):
        raise ValueError('Every actual new route must explicitly declare continuous_upright')
    if any(r['motion']=='FOOT_BEARING_TURN' for r in directory['legs']) or any(key in owner.get('ground_guides',{}) for key in ('dock_foundations','dock_source_sha256')) or any(key in owner for key in ('turn_stations','foot_stations')):
        raise ValueError('New continuous mode rejects all old turn-station declarations')
    if owner.get('ground_guides',{}).get('mode')!='continuous_upright':raise ValueError('Actual explicit continuous owner ground guide mode required')
    units=owner['units'];gates=owner['gates'];roster={u['variant']:u for u in directory['units']}
    if len(units)!=3 or len(directory['units'])!=3 or {u['variant'] for u in units}!={0,1,2} or set(roster)!={0,1,2} or not gates:
        raise ValueError('Actual three original units and complete explicitly declared Root gate set required')
    sealed_front_specs(gates)
    rows=[];identities=set();gate_resources=set()
    def add(identity,role):
        identity=str(uuid.UUID(identity))
        if identity in identities:raise ValueError('Declared controller UUID aliased: '+identity)
        identities.add(identity);rows.append({'uuid':identity,'role':role})
    for u in units:
        actual=roster[u['variant']]
        if u['eva']!=actual['eva'] or u['plug']!=actual['plug']:raise ValueError('Owner original EVA/plug differs from actual directory roster')
        for key,role in [('gantry','original_gantry'),('carrier_controller','original_carrier')]:add(u[key]['id'],role)
        add(u['crane']['visual']['id'],'original_crane')
        if u['carrier_controller']['id']!=java_uuid(f"projectseele:r52:original-carrier:{bundle['epoch']}:{u['eva']}"):
            raise ValueError('Explicit original carrier declaration does not match its production name identity')
    for gate in gates:
        if gate['kind'] not in ('HANGAR','SILO') or gate['resource'] in gate_resources:raise ValueError('Exact unique typed Root gate declaration required')
        gate_resources.add(gate['resource']);add(gate['visual'],'hangar_gate' if gate['kind']=='HANGAR' else 'silo_gate')
    declared_doors=[r['id'] for r in directory['resources'] if r['kind']=='DOOR']
    if len(declared_doors)!=len(set(declared_doors)) or gate_resources!=set(declared_doors):raise ValueError('Owner gate resources differ from exact actual Directory DOOR declarations')
    if cannon is not None:add(cannon['cannon_uuid'],'fixed_cannon')
    elif 'yashima_cannon_hatch' in gate_resources:raise ValueError('Deferred cannon cannot retain an unused cannon gate in scope124')
    roles={role:sum(row['role']==role for row in rows) for role in set(row['role'] for row in rows)}
    if any(roles.get(role)!=3 for role in ('original_carrier','original_gantry','original_crane')) or roles.get('fixed_cannon',0)!=(1 if cannon is not None else 0) or roles.get('hangar_gate',0)+roles.get('silo_gate',0)!=len(gates):
        raise ValueError('Declared controller role coverage differs from the actual manifest')
    return rows

def validate_legacy_floor_bindings(owner,directory):
    overlay=owner['mechanism_sources'].get('mesh/legacy_floor_recesses_r52.json')
    if not isinstance(overlay,str) or len(overlay)!=64 or any(c not in '0123456789abcdef' for c in overlay):raise ValueError('Actual independent Legacy floor overlay source authority required')
    rails=[r['mechanical_rail'] for r in directory['runtime']['bindings'] if 'mechanical_rail' in r]
    legacy=[s for s in rails if s['kind']=='LEGACY_RUNNING_HEAD']
    if len(rails)!=18 or len(legacy)!=9 or any(s.get('floor_overlay_sha256')!=overlay for s in legacy) or any('floor_overlay_sha256' in s for s in rails if s['kind']!='LEGACY_RUNNING_HEAD'):raise ValueError('Actual9 Legacy rail pairs must preserve their separate selected floor overlay binding')
    for field,source in [('service_overlay_sha256','mesh/legacy_service_bypass_r52.json'),('level_overlay_sha256','mesh/legacy_compact_level_r52.json'),('deep_frame_sha256','mesh/legacy_deep_frame_r53.json')]:
        selected=owner['mechanism_sources'].get(source)
        if not isinstance(selected,str)or len(selected)!=64 or any(c not in '0123456789abcdef'for c in selected)or any(s.get(field)!=selected for s in legacy)or any(field in s for s in rails if s['kind']!='LEGACY_RUNNING_HEAD'):raise ValueError('Actual original rail pairs must retain their exact independent '+field)

def declared_controller_inputs(bundle_path):
    bundle_path=Path(bundle_path).resolve();bundle=read(bundle_path);documents={}
    for key in ('directory','mechanical_owner','upright_guideway')+ (('fixed_cannon',) if 'fixed_cannon' in bundle else ()):
        _,path=reference(bundle_path.parent,bundle[key],'file');documents[key]=read(path)
        exact_authority(documents[key],bundle['epoch'],bundle['directory_fingerprint'],key)
    guide=documents['upright_guideway'];owner=documents['mechanical_owner']
    if guide.get('schema')!='projectseele.r52.upright-captured-paths.v1' or bundle['upright_guideway']['sha256']!=owner['ground_guides']['paths_sha256'] or guide.get('model_source_sha256')!=owner['ground_guides']['source_sha256'] or guide.get('head_transfer_source_sha256')!=owner['mechanism_sources'].get('mesh/outer_head_transfer_r53.json') or not guide.get('anchors') or not guide.get('pieces') or not guide.get('paths'):raise ValueError('Actual nonempty guideway bytes/model/anchors must match exact owner source binding')
    _,owner_path=reference(bundle_path.parent,bundle['mechanical_owner'],'file')
    validate_seal_phase_tables(owner['gates'],lambda g:phase_rows(g,owner_path.parent))
    validate_legacy_floor_bindings(owner,documents['directory'])
    rows=expected_controllers(bundle,owner,documents['directory'],documents.get('fixed_cannon'))
    return bundle,rows

